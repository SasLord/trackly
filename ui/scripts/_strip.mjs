// Общая вычистка комментариев для гейтов `check-*.mjs` (ревью 41.12, WR-01).
//
// ЛОВУШКА, ради которой модуль существует. Прежние локальные копии сначала
// вырезали ВСЕ блочные комментарии (`/\/\*[\s\S]*?\*\//g`), а строчные — вторым
// проходом. Такой порядок не знает, что `/*` внутри строчного комментария
// блок НЕ открывает: строка `// шаблоны лежат в templates/*.html` «открывала»
// блок, который закрывался на ближайшем `*/` ниже по файлу, и весь код между
// ними молча выпадал из скана (так из проверки пропадал TemplateEditor.svelte).
// Гейт при этом печатал PASS — дыра невидима, пока в стёртом куске не появится
// нарушение.
//
// Поэтому здесь ОДИН проход слева направо: комментарий съедается целиком в
// порядке появления, и `/*` внутри `//` уже не может открыть блок.
//
// Контракт: длина строки и все переводы строк сохраняются (остальные символы
// комментария заменяются пробелами), поэтому индексы и номера строк в
// исходнике и в результате совпадают. Кавычечная эвристика на чётность:
// `//` и `/*` после нечётного числа кавычек (' " `) на той же строке — часть
// строкового литерала, а не комментарий. Это grep-эвристика, не парсер.
//
// Зависимостей нет.

/**
 * Затирает HTML-, блочные и строчные комментарии.
 * @param {string} src
 * @returns {string}
 */
export function stripComments(src) {
  const out = src.split('');
  const blank = (from, to) => {
    for (let i = from; i < to && i < src.length; i++) if (out[i] !== '\n') out[i] = ' ';
  };
  let lineStart = 0;
  let i = 0;
  while (i < src.length) {
    const c = src[i];
    if (c === '\n') {
      lineStart = i + 1;
      i++;
      continue;
    }
    if (src.startsWith('<!--', i)) {
      const end = src.indexOf('-->', i + 4);
      const to = end < 0 ? src.length : end + 3;
      blank(i, to);
      i = to;
      continue;
    }
    if (c === '/' && (src[i + 1] === '/' || src[i + 1] === '*')) {
      const quotes = (src.slice(lineStart, i).match(/['"`]/g) ?? []).length;
      if (quotes % 2 === 0) {
        let to;
        if (src[i + 1] === '/') {
          const nl = src.indexOf('\n', i);
          to = nl < 0 ? src.length : nl;
        } else {
          const end = src.indexOf('*/', i + 2);
          to = end < 0 ? src.length : end + 2;
        }
        blank(i, to);
        // перевод строки внутри блока сохраняется; начало строки пересчитывается
        const lastNl = src.lastIndexOf('\n', to - 1);
        if (lastNl >= i) lineStart = lastNl + 1;
        i = to;
        continue;
      }
    }
    i++;
  }
  return out.join('');
}
