// Тексты отказов отправки сообщения чата по машинному коду (вынесено из ChatComposer, фаза 43-10).
// Серверные тексты не показываются; формулировки не менять без согласования.

export function rejectText(code: string | null): string {
  switch (code) {
    case 'too_long':
      return 'Сообщение длиннее 4000 символов. Сократите его и отправьте снова.';
    case 'closed':
      return 'Заявка закрыта — сообщение не отправлено.';
    case 'no_chat':
    case 'forbidden':
      return 'Нет доступа к переписке этой заявки.';
    default:
      return 'Не удалось отправить сообщение. Проверьте подключение и попробуйте ещё раз.';
  }
}
