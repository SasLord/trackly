//! `embed_migrations!("../../migrations")` (src/db/migrations.rs) читает каталог
//! на этапе компиляции, но cargo об этом не знает: новый `V*.sql` не вызывает
//! пересборку, и уже собранная библиотека молча остаётся без миграции (так
//! V052 не попала в сплошной прогон, пока не сменился какой-нибудь `.rs`).
//! `rerun-if-changed` на каталог заставляет cargo следить за всем его
//! содержимым.

fn main() {
    println!("cargo:rerun-if-changed=../../migrations");
}
